def parse_sienna_schema_object(kind: SiennaObjectKind, data: dict[str, object]) -> SiennaSchemaModel:
    """Parse one object through its fixed-slot registered model.

    :param kind: Declared Sienna schema type.
    :param data: Raw schema-validated JSON object.
    :return: Concrete typed Sienna schema model.
    """
    from VeraGridEngine.IO.sienna.devices.schema_registry import get_sienna_object_parser
    parser = get_sienna_object_parser(kind)
    return parser(data)


def parse_sienna_schema_union(kinds: tuple[SiennaObjectKind, ...], data: dict[str, object]) -> object:
    """Parse one discriminated nested object through its declared candidate kinds.

    :param kinds: Schema kinds permitted by the enclosing ``oneOf`` field.
    :param data: Nested JSON object.
    :return: The first concrete fixed-slot model accepting the object.
    :raises ValueError: When no declared candidate accepts the nested object.
    """
    errors: list[str] = list()
    for kind in kinds:
        try:
            return parse_sienna_schema_object(kind=kind, data=data)
        except ValueError as error:
            errors.append(str(error))
    raise ValueError(f"Nested Sienna union does not match declared kinds {kinds}: {errors}")
